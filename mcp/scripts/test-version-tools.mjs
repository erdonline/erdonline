#!/usr/bin/env node
import assert from 'node:assert/strict';
import {ErdApiClient} from '../dist/erd-api.js';
import {
  diffVersionDetails,
  draftDdlFromVersion,
} from '../dist/version-tools.js';

const beforeProject = {
  modules: [{
    name: 'core',
    entities: [{
      title: 'users',
      remark: 'Approved user contract',
      fields: [
        {name: 'id', dataType: 'BIGINT', pk: true, autoIncrement: true},
        {name: 'email', dataType: 'VARCHAR(255)', notNull: true},
        {name: 'legacy_name', dataType: 'VARCHAR(80)'},
      ],
    }, {
      title: 'audit_old',
      fields: [{name: 'id', dataType: 'BIGINT', pk: true}],
    }],
  }],
};

const afterProject = {
  modules: [{
    name: 'core',
    entities: [{
      title: 'users',
      remark: 'Approved identity contract',
      fields: [
        {name: 'id', dataType: 'BIGINT', pk: true, autoIncrement: true},
        {name: 'email', dataType: 'VARCHAR(320)', notNull: true},
        {name: 'display_name', dataType: 'VARCHAR(80)'},
        {name: 'created_at', dataType: 'TIMESTAMP', notNull: true, defaultValue: 'CURRENT_TIMESTAMP'},
      ],
    }, {
      title: 'audit_log',
      fields: [{name: 'id', dataType: 'BIGINT', pk: true}],
    }],
  }],
};

const responses = {
  v1: {id: 'v1', version: '1.0.0', projectJson: beforeProject},
  v2: {id: 'v2', version: '1.1.0', projectJson: afterProject},
};

const originalFetch = globalThis.fetch;
const fetched = [];
globalThis.fetch = async (url, init) => {
  const href = String(url);
  fetched.push({href, init});
  const id = href.endsWith('/v1') ? 'v1' : href.endsWith('/v2') ? 'v2' : '';
  return new Response(
    JSON.stringify({code: 200, data: responses[id]}),
    {status: 200, headers: {'Content-Type': 'application/json'}},
  );
};

try {
  const api = new ErdApiClient({
    baseUrl: 'https://unit.invalid',
    pat: 'erd_pat_unit',
  });
  const [before, after] = await Promise.all([
    api.getVersion('project 1', 'v1'),
    api.getVersion('project 1', 'v2'),
  ]);
  const diff = diffVersionDetails(before, after, 'v1', 'v2');

  assert.equal(diff.fromVersion.id, 'v1');
  assert.equal(diff.toVersion.id, 'v2');
  assert.deepEqual(diff.summary, {
    tablesAdded: 1,
    tablesRemoved: 1,
    tablesChanged: 1,
    columnsAdded: 2,
    columnsRemoved: 1,
    columnsModified: 1,
  });
  assert.deepEqual(diff.tables.renameCandidates, [{
    from: 'audit_old',
    to: 'audit_log',
    confidence: 'high',
    reason: 'identical column names and structural shapes',
  }]);
  assert.equal(
    diff.tables.changed[0].columns.renameCandidates[0].from,
    'legacy_name',
  );
  assert.equal(
    diff.tables.changed[0].columns.renameCandidates[0].to,
    'display_name',
  );
  assert.equal(fetched.length, 2);
  assert.match(fetched[0].href, /projects\/project%201\/versions\/v1$/);
  assert.equal(fetched[0].init.method, 'GET');

  const preview = draftDdlFromVersion(after, 'v2', 'postgresql', 'users');
  assert.equal(preview.previewOnly, true);
  assert.equal(preview.executed, false);
  assert.equal(preview.statementCount, 1);
  assert.match(preview.ddl, /^CREATE TABLE "users"/);
  assert.match(preview.ddl, /"id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL/);
  assert.match(preview.ddl, /PRIMARY KEY \("id"\)/);
  assert.match(preview.warnings[0], /never connects to a database/);
  assert.match(preview.warnings[0], /never executes SQL/);

  assert.throws(
    () => draftDdlFromVersion(
      {id: 'v3', projectJson: afterProject},
      'v3',
      'mysql',
    ),
    /named saved version/,
  );
} finally {
  globalThis.fetch = originalFetch;
}

console.log('PASS version tools: semantic diff + preview-only DDL + mocked fetch');
